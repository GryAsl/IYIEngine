# SPEC.md drift report
# ---------------------------------------------------------------------------

def _spec_text(engine_root: Path, *names: str) -> str:
    """Concatenate whichever spec documents exist, for a presence search."""
    out = []
    for n in names:
        f = engine_root / "docs" / n
        # SPEC.md is an index since 2026-11-11; its sections live in docs/spec/*.md.
        for g in [f] + (sorted((engine_root / "docs" / "spec").glob("*.md")) if n == "SPEC.md" else []):
            if g.exists():
                out.append(g.read_text(encoding="utf-8", errors="replace"))
    return "\n".join(out)


def report_spec_drift(engine_root: Path, engine_gen: str, ui_gen: str, loc_gen: str = "", audio_gen: str = "") -> None:
    """Report symbols the bindings expose but the spec does not document.

    Presence-only: this answers "is this symbol mentioned in the spec", not
    "does the documented signature still match". Signature-level comparison
    would need a Markdown API parser and is deliberately out of scope.
    The spec is never edited - reporting is the whole contract.
    """
    targets = [
        ("engine", engine_gen, _spec_text(engine_root, "SPEC.md"), "SPEC.md"),
        ("engine.ui", ui_gen,
         _spec_text(engine_root, "SPEC-IYIUI.md", "SPEC.md"), "SPEC-IYIUI.md"),
    ]
    if loc_gen:
        targets.append(("engine.loc", loc_gen, _spec_text(engine_root, "SPEC.md"), "SPEC.md"))
    if audio_gen:
        targets.append(("engine.audio", audio_gen, _spec_text(engine_root, "SPEC.md"), "SPEC.md"))
    print("")
    print("SPEC drift report (presence only; the spec is never edited):")
    drift = 0
    checked = 0
    for module, gen, spec, label in targets:
        if not spec:
            print("  [%s] %s not found - skipped" % (module, label))
            continue
        for name in sorted(set(re.findall(r"^def (\w+)\(", gen, re.M))):
            checked += 1
            if name.startswith("_"):
                # The private policy is a decision, so keep it visible.
                print("  [%s] %s: internal, not required in %s - OK"
                      % (module, name, label))
            elif name in spec:
                pass  # Documented. Only drift is worth printing.
            else:
                print("  [%s] %s: MISSING from %s - DRIFT"
                      % (module, name, label))
                drift += 1
    print("  %d symbol(s) checked, %d undocumented." % (checked, drift))
    print("")


