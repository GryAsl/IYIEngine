def arg_type(name: str, func_name: str = "", derived: Optional[str] = None) -> str:
    """Explicit override, else the type the lambda declares, else the name tables."""
    if func_name and (func_name, name) in FUNC_ARG_OVERRIDES:
        return FUNC_ARG_OVERRIDES[(func_name, name)]
    if derived:
        return derived
    if name in ARG_TYPE_MAP:
        return ARG_TYPE_MAP[name]
    if name.endswith("_path") or name.endswith("_name"):
        return "str"
    if name.endswith("_color"):
        return "Color"
    if name.endswith("_size") and "font" not in name:
        return "float"
    if name.startswith("is_") or name.startswith("has_") or name.startswith("allow_"):
        return "bool"
    return "Any"


