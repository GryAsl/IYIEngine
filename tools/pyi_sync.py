def wrap_generated(content: str) -> str:
    """Wrap content in BEGIN/END markers."""
    return BEGIN_MARKER + "\n" + content.rstrip("\n") + "\n" + END_MARKER + "\n"


def assemble_file(existing: str, file_header: str, generated: str) -> str:
    """
    Produce the final file content:
    - If markers exist: preserve everything outside them, replace the region between them.
    - If no markers exist (first run): produce file_header + generated_region.
      All existing content is discarded in favour of the fully-generated version.
      This is the "migrate all hand-written symbols" step.
    """
    if BEGIN_MARKER in existing:
        # Markers exist - preserve outside content, replace inside
        before_start = existing.index(BEGIN_MARKER)
        end_idx = existing.find(END_MARKER)
        if end_idx == -1:
            # Malformed: BEGIN without END - replace from BEGIN to end of file
            before = existing[:before_start]
            after = ""
        else:
            before = existing[:before_start]
            after = existing[end_idx + len(END_MARKER):]
            # Strip leading newline from after
            if after.startswith("\n"):
                after = after[1:]

        for line in file_header.splitlines():
            if line.startswith("from . import ") and line not in before:
                before = before.rstrip("\n") + "\n" + line + "\n\n"

        result = before + wrap_generated(generated)
        if after.strip():
            result += "\n" + after
        return result
    else:
        # No markers: first-run migration - full generated file
        return file_header + wrap_generated(generated)


def stub_symbols(text: str) -> set[str]:
    """`func`, `CONSTANT`, `Class` and `Class.member` names inside the generated region of a stub."""
    if BEGIN_MARKER in text:
        text = text[text.index(BEGIN_MARKER):text.find(END_MARKER) if END_MARKER in text else None]
    names, cls = set(), ""
    for line in text.splitlines():
        m = re.match(r'(class|def) (\w+)|(\w+)\s*:|    (?:def )?(\w+)\s*[(:]', line)
        if not m:
            continue
        if m.group(1) == "class":
            cls = m.group(2)
            names.add(cls)
        elif m.group(1) == "def" or m.group(3):
            cls = ""
            names.add(m.group(2) or m.group(3))
        elif cls:
            names.add(f"{cls}.{m.group(4)}")
    return names


def dropped_bound_symbols(old: str, new: str, binding_text: str) -> list[str]:
    """Symbols the old stub had, the new one lacks, and the bindings still define: a parser gap, not a
    removed binding. Writing would silently delete working API from the stubs."""
    bound = set(re.findall(r'(?:\.def\w*|attr)\s*\(\s*"(\w+)"|py::(?:class_|enum_)<[^;(]*\(\s*\w+\s*,\s*"(\w+)"', binding_text))
    bound = {a or b for a, b in bound}
    return sorted(n for n in stub_symbols(old) - stub_symbols(new) if n.split(".")[-1] in bound)


def read_stub(path: Path) -> str:
    return path.read_text(encoding="utf-8") if path.exists() else ""


def write_stub(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8", newline="\n")


