def load_overrides(stubs_root: Path) -> dict:
    p = stubs_root / "typings" / "pyi_overrides.json"
    if p.exists():
        return json.loads(p.read_text(encoding="utf-8"))
    return {}


def ensure_override_manifest(stubs_root: Path) -> None:
    p = stubs_root / "typings" / "pyi_overrides.json"
    if not p.exists():
        p.parent.mkdir(parents=True, exist_ok=True)
        template = {
            "_comment": (
                "Override manifest for pyi_sync.py. "
                "Keys are function names (e.g. 'spawn_actor') or 'engine.ui.func_name'. "
                "Add an entry here for any symbol the parser cannot derive."
            ),
            "_example_func": {
                "args": [
                    {"name": "path", "type": "str"},
                    {"name": "size", "type": "int", "default": "32"}
                ],
                "return": "str | None"
            }
        }
        p.write_text(json.dumps(template, indent=4), encoding="utf-8")
        print(f"  Created override manifest: {p}")


