"""
pyi_sync.py - IYI Engine pybind11 -> .pyi stub synchronization tool.

Statically parses EngineBindings.cpp, RaylibBindings.cpp, IYIUIBindings.cpp,
LocalizationBindings.cpp, and AudioBindings.cpp to generate typed Python stubs in the engine's shared typings/engine/ (--stubs-root overrides the repository root).

Usage:
    python tools/pyi_sync.py --engine-root <path> --stubs-root <path> [--check | --diff | --write]

Modes:
    --check   Exit non-zero if generated content differs from disk. (CI gate)
    --diff    Print unified diff without writing anything.
    --write   Apply the generated content to disk.

Scope and limits:
    - Parses m.def, py::class_, chained .def, .def_readwrite, .def_readonly,
      .def_property, .def_property_readonly, py::arg defaults, multi-line bindings.
    - Handles engine, engine.ui, engine.loc, and engine.audio submodules.
    - Maps C++ raylib/IYI types to Python stubs (Vector2, Color, GameActor, etc.)
    - Types come from the code first: a binding lambda's own parameter types (matched to its
      py::arg names in order), its "-> T" return or, without an arrow, a body with no
      "return <value>" (= None); a def_readonly/def_readwrite member's declaration in the
      engine headers. The name tables below are the fallback for what the code cannot say
      (bound member-function pointers, auto returns), so a new binding written like the
      existing ones needs no table edit.
    - Does NOT parse arbitrary C++. Symbols the parser cannot safely resolve are
      reported with source file, line, symbol name and reason; tool exits non-zero.
    - Override/manifest file at <stubs-root>/typings/pyi_overrides.json supplies
      hand-written signatures for anything the parser cannot derive.
    - Stub files have a generated region (BEGIN/END markers). Content outside markers
      is preserved verbatim. On first write, entire file becomes the generated region
      (migrating all hand-written symbols).
    - Underscore-prefixed bindings are emitted with an internal-API comment.
    - SPEC.md API drift is reported (not fixed).

No new dependencies beyond Python stdlib.
"""

