def unified_diff(a: str, b: str, from_label: str, to_label: str) -> str:
    return "".join(difflib.unified_diff(
        a.splitlines(keepends=True),
        b.splitlines(keepends=True),
        fromfile=from_label,
        tofile=to_label,
    ))


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> int:
    parser = argparse.ArgumentParser(
        prog="pyi_sync.py",
        description=(
            "IYI Engine pybind11 -> .pyi stub synchronization tool.\n\n"
            "Parses EngineBindings.cpp, RaylibBindings.cpp, IYIUIBindings.cpp,\n"
            "LocalizationBindings.cpp and writes stubs to typings/engine/__init__.pyi,\n"
            "typings/engine/ui.pyi, and typings/engine/loc.pyi.\n\n"
            "Scope: m.def, py::class_, .def_readwrite, .def_readonly, .def_property,\n"
            ".def_property_readonly, py::arg with defaults, multi-line bindings.\n"
            "Limit: does not parse arbitrary C++. Unknown symbols are reported with\n"
            "source:line:symbol:reason; tool exits 1. Provide signatures via override\n"
            "manifest at <stubs-root>/typings/pyi_overrides.json."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    default_engine_root = Path(__file__).resolve().parent.parent
    parser.add_argument("--engine-root", default=str(default_engine_root),
                        help="IYIEngine repository root (contains src/, docs/).")
    parser.add_argument("--stubs-root",
                        help="Repository root containing typings/engine/*.pyi (default: --engine-root).")

    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true",
                      help="Exit 1 if generated content differs from disk.")
    mode.add_argument("--diff",  action="store_true",
                      help="Show unified diff without writing.")
    mode.add_argument("--write", action="store_true",
                      help="Write generated content to disk.")

    args = parser.parse_args()

    engine_root = Path(args.engine_root).resolve()
    stubs_root  = Path(args.stubs_root).resolve() if args.stubs_root else engine_root

    if not engine_root.exists():
        print(f"ERROR: --engine-root not found: {engine_root}", file=sys.stderr)
        return 2
    if not stubs_root.exists():
        print(f"ERROR: --stubs-root not found: {stubs_root}", file=sys.stderr)
        return 2

    overrides = load_overrides(stubs_root)

    print(f"[pyi_sync] engine-root : {engine_root}")
    print(f"[pyi_sync] stubs-root  : {stubs_root}")
    print()

    all_errors: list[ParseError] = []

    print("[pyi_sync] Parsing engine bindings (EngineBindings.cpp, RaylibBindings.cpp)...")
    engine_gen, engine_errors = build_engine_generated(engine_root, overrides)
    all_errors.extend(engine_errors)

    print("[pyi_sync] Parsing UI bindings (IYIUIBindings.cpp)...")
    ui_gen, ui_errors = build_ui_generated(engine_root, overrides)
    all_errors.extend(ui_errors)

    print("[pyi_sync] Parsing localization bindings (LocalizationBindings.cpp)...")
    loc_gen, loc_errors = build_loc_generated(engine_root, overrides)
    all_errors.extend(loc_errors)

    print("[pyi_sync] Parsing audio bindings (AudioBindings.cpp)...")
    audio_gen, audio_errors = build_audio_generated(engine_root, overrides)
    all_errors.extend(audio_errors)

    init_pyi  = stubs_root / "typings" / "engine" / "__init__.pyi"
    ui_pyi    = stubs_root / "typings" / "engine" / "ui.pyi"
    loc_pyi   = stubs_root / "typings" / "engine" / "loc.pyi"
    audio_pyi = stubs_root / "typings" / "engine" / "audio.pyi"

    existing_init  = read_stub(init_pyi)
    existing_ui    = read_stub(ui_pyi)
    existing_loc   = read_stub(loc_pyi)
    existing_audio = read_stub(audio_pyi)

    new_init  = assemble_file(existing_init,  ENGINE_FILE_HEADER, engine_gen)
    new_ui    = assemble_file(existing_ui,    UI_FILE_HEADER,     ui_gen)
    new_loc   = assemble_file(existing_loc,   LOC_FILE_HEADER,    loc_gen)
    new_audio = assemble_file(existing_audio, AUDIO_FILE_HEADER,  audio_gen)

    init_diff  = unified_diff(existing_init,  new_init,  str(init_pyi),  str(init_pyi)  + " (new)")
    ui_diff    = unified_diff(existing_ui,    new_ui,    str(ui_pyi),    str(ui_pyi)    + " (new)")
    loc_diff   = unified_diff(existing_loc,   new_loc,   str(loc_pyi),   str(loc_pyi)   + " (new)")
    audio_diff = unified_diff(existing_audio, new_audio, str(audio_pyi), str(audio_pyi) + " (new)")
    has_changes = bool(init_diff or ui_diff or loc_diff or audio_diff)

    binding_text = "".join(p.read_text(encoding="utf-8", errors="replace")
                           for p in (engine_root / "src").glob("*Bindings.cpp"))
    dropped = [f"{path.name}: {name}"
               for path, old, new in ((init_pyi, existing_init, new_init), (ui_pyi, existing_ui, new_ui),
                                      (loc_pyi, existing_loc, new_loc), (audio_pyi, existing_audio, new_audio))
               for name in dropped_bound_symbols(old, new, binding_text)]
    if dropped:
        print(f"[pyi_sync] The generator would DROP {len(dropped)} symbol(s) that are still bound (parser gap):")
        for d in dropped:
            print(f"  {d}")
        print()

    # Report parse errors
    if all_errors:
        print(f"[pyi_sync] Parser issues ({len(all_errors)}):")
        for e in all_errors:
            print(str(e))
        print()

    # Report SPEC drift
    report_spec_drift(engine_root, engine_gen, ui_gen, loc_gen, audio_gen)

    if args.diff:
        if init_diff:
            print(f"=== {init_pyi} ===")
            print(init_diff)
        if ui_diff:
            print(f"=== {ui_pyi} ===")
            print(ui_diff)
        if loc_diff:
            print(f"=== {loc_pyi} ===")
            print(loc_diff)
        if audio_diff:
            print(f"=== {audio_pyi} ===")
            print(audio_diff)
        if not has_changes:
            print("[pyi_sync] No differences - stubs are up to date.")

    elif args.check:
        if has_changes:
            print("[pyi_sync] STUBS OUT OF DATE. Run --write to update.")
            if init_diff:
                print(f"  {init_pyi}: differs")
            if ui_diff:
                print(f"  {ui_pyi}: differs")
            if loc_diff:
                print(f"  {loc_pyi}: differs")
            if audio_diff:
                print(f"  {audio_pyi}: differs")
            return 1
        print("[pyi_sync] Stubs are up to date.")

    elif args.write:
        if all_errors or dropped:
            # Every unresolved symbol would vanish from the stubs; never write a lossy result.
            print("[pyi_sync] NOT WRITTEN: fix the parser issues / dropped symbols above first "
                  "(or add signatures to typings/pyi_overrides.json).")
            return 1
        if has_changes:
            write_stub(init_pyi,  new_init)
            write_stub(ui_pyi,    new_ui)
            write_stub(loc_pyi,   new_loc)
            write_stub(audio_pyi, new_audio)
            ensure_override_manifest(stubs_root)
            print(f"[pyi_sync] Written: {init_pyi}")
            print(f"[pyi_sync] Written: {ui_pyi}")
            print(f"[pyi_sync] Written: {loc_pyi}")
            print(f"[pyi_sync] Written: {audio_pyi}")
        else:
            print("[pyi_sync] Stubs already up to date - nothing written.")

    return 1 if all_errors else 0


if __name__ == "__main__":
    # Windows consoles default to cp1252; a stray non-ASCII character in any
    # message would otherwise abort the whole run (it once broke --help).
    for _stream in (sys.stdout, sys.stderr):
        try:
            _stream.reconfigure(encoding="utf-8", errors="replace")
        except AttributeError:
            pass
    sys.exit(main())
