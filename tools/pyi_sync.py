# Default/init maps (hard-coded from binding sources - parser supplements these)
# ---------------------------------------------------------------------------

CPP_DEFAULT_MAP: dict[str, str] = {
    "true":       "True",
    "false":      "False",
    '""':         '""',
    "nullptr":    "None",
    "py::none()": "None",
}

def cpp_default_to_py(val: str) -> str:
    val = val.strip().rstrip(",").strip()
    if val in CPP_DEFAULT_MAP:
        return CPP_DEFAULT_MAP[val]
    if val.startswith("py::none("):          # the arg regex stops at the call's ')'
        return "None"
    # float literal: 0.0f -> 0.0
    if val.endswith("f") and re.match(r'^-?\d+(\.\d+)?f$', val):
        return val[:-1]
    # string literal
    if val.startswith('"') and val.endswith('"'):
        return val
    # integer
    if re.match(r'^-?\d+$', val):
        return val
    # Vector2{...} or similar struct init -> use ...
    return "..."


def extract_py_args(text: str) -> list[tuple[str, Optional[str]]]:
    """Extract py::arg("name") [= default] pairs from binding text (not from inside the lambda's body)."""
    text = without_lambda_body(text)
    results: list[tuple[str, Optional[str]]] = []
    # Match py::arg("name") optionally = value (up to next comma/close-paren)
    pattern = re.compile(
        r'py::arg\("([^"]+)"\)'
        r'(?:\s*=\s*((?:[^,\n\)]+(?:\{[^}]*\})?[^,\n\)]*)))?',
        re.DOTALL
    )
    for m in pattern.finditer(text):
        name = m.group(1)
        raw = m.group(2)
        default = cpp_default_to_py(raw) if raw is not None else None
        results.append((name, default))
    return results


def extract_lambda_return(text: str) -> Optional[str]:
    """Extract C++ return type from lambda: '(...) -> T {'."""
    m = re.search(r'\)\s*->\s*([A-Za-z0-9_:<>\s\*&,]+?)\s*\{', text, re.DOTALL)
    if m:
        raw = m.group(1).strip()
        # Remove trailing policy annotations if caught
        raw = re.split(r'\s*,\s*py::', raw)[0].strip()
        return raw
    return None


def _lambda_span(text: str) -> Optional[tuple[int, int]]:
    """(start, end) of the first binding lambda's parameter list contents '[...](here)'."""
    m = re.search(r'\[[^\]\[]*\]\s*\(', text)
    if not m:
        return None
    end = find_block_end(text, m.end())
    return m.end(), end - 1


def without_lambda_body(text: str) -> str:
    """The binding text minus the first lambda's `{ body }`: a py::arg there is a call, not a parameter."""
    span = _lambda_span(text)
    start = text.find("{", span[1]) if span else -1
    if start < 0:
        return text
    depth = 0
    for i in range(start, len(text)):
        depth += {"{": 1, "}": -1}.get(text[i], 0)
        if depth == 0:
            return text[:start] + text[i + 1:]
    return text


def extract_lambda_params(text: str) -> Optional[list[str]]:
    """C++ types of the binding lambda's parameters, in order; None when the binding has no lambda."""
    span = _lambda_span(text)
    if span is None:
        return None
    inner = text[span[0]:span[1]].strip()
    if not inner:
        return []
    types = []
    for param in _split_template_args(inner):
        param = param.split('=')[0].strip()
        m = re.match(r'(.+?)\s*\b([A-Za-z_]\w*)$', param)
        types.append(m.group(1).strip() if m else param)
    return types


def lambda_returns_nothing(text: str) -> bool:
    """True for a binding lambda with no '-> T' and no 'return <value>' in its body: it returns None."""
    span = _lambda_span(text)
    if span is None:
        return False
    after = text[span[1] + 1:]
    head = re.match(r'\s*(mutable\s*)?\{', after)
    if not head:                       # an arrow (or anything else) before the body
        return False
    depth, i = 0, head.end() - 1
    while i < len(after):
        if after[i] == '{':
            depth += 1
        elif after[i] == '}':
            depth -= 1
            if depth == 0:
                break
        i += 1
    body = after[head.end():i]
    return re.search(r'\breturn\s+[^;\s]', body) is None


def lambda_arg_types(text: str, py_args: list, skip_self: bool) -> list[Optional[str]]:
    """Python types for py_args from the lambda's parameters (None where the code does not say).
    A method lambda's first parameter is the bound object, which has no py::arg."""
    params = extract_lambda_params(text)
    if params is None:
        func = bound_header_func(text)   # &Api::Name / &Class::Method: the header says
        params = func[1] if func else None
        skip_self = False
    if params is None:
        return [None] * len(py_args)
    params = [t for t in params if t.split()[0] not in ("py::kwargs", "py::args")]   # **kwargs / *args: no py::arg
    if skip_self and len(params) == len(py_args) + 1:
        params = params[1:]
    if len(params) != len(py_args):
        return [None] * len(py_args)
    return [map_cpp_type(t) for t in params]


_HEADER_FIELDS: dict[tuple[str, str], str] = {}
_HEADER_FUNCS: dict[tuple[str, str], tuple[str, list[str], str]] = {}


def load_header_fields(include_dir: Path) -> None:
    """Field declarations of every struct/class in the engine headers: (Class, Field) -> C++ type.
    Lets def_readonly/def_readwrite(&Class::Field) find its type without a table entry."""
    if _HEADER_FIELDS or not include_dir.is_dir():
        return
    for header in include_dir.rglob("*.h"):
        text = re.sub(r'//[^\n]*', '', header.read_text(encoding="utf-8", errors="replace"))
        for m in re.finditer(r'\b(?:struct|class)\s+(\w+)[^;{]*\{', text):
            depth, i = 1, m.end()
            while i < len(text) and depth:
                depth += {'{': 1, '}': -1}.get(text[i], 0)
                i += 1
            body = text[m.end():i - 1]
            for decl in re.finditer(r'^\s*([A-Za-z_][\w:<>,\s\*&]*?[\w>\*&])\s+([A-Za-z_]\w*)\s*(?:=[^;]*|\{[^;]*\})?((?:\s*,\s*[A-Za-z_]\w*\s*(?:=[^,;]*)?)*)\s*;',
                                    body, re.MULTILINE):
                ctype = decl.group(1).strip()
                if ctype in ("return", "using", "typedef") or "(" in decl.group(0):
                    continue
                names = [decl.group(2)] + re.findall(r',\s*([A-Za-z_]\w*)', decl.group(3) or "")
                for name in names:
                    _HEADER_FIELDS.setdefault((m.group(1), name), ctype)


def load_header_funcs(include_dir: Path) -> None:
    """Function declarations of the engine headers: (Scope, Name) -> (C++ return, [C++ param types], comment).
    Scope is the enclosing class/struct/namespace, so a binding like `&Api::IsAgentRun` or
    `&UICanvas::GetHovered` gets its signature (and Api.h's trailing comment) without a table entry."""
    if _HEADER_FUNCS or not include_dir.is_dir():
        return
    decl_re = re.compile(r'^[ \t]*(?:(?:static|inline|virtual|IYI_API)\s+)*([A-Za-z_][\w:<>,\s\*&]*?[\w>\*&])\s+'
                         r'([A-Za-z_]\w*)\s*\(([^()]*)\)\s*(?:const\s*)?(?:override\s*)?(?:;[ \t]*(?://[ \t]*(.*))?$|\{)', re.MULTILINE)
    headers = sorted(include_dir.rglob("*.h"), key=lambda h: h.name != "Api.h")   # Api.h wins name clashes
    for header in headers:
        raw = header.read_text(encoding="utf-8", errors="replace")
        # Block comments out, line comments kept (they are the docs); a scope is the innermost one opened above.
        text = re.sub(r'/\*.*?\*/', lambda c: re.sub(r'[^\n]', ' ', c.group(0)), raw, flags=re.S)
        code = re.sub(r'//[^\n]*', lambda c: ' ' * len(c.group(0)), text)   # `} // namespace X` opens nothing
        scopes = []   # (open, close, name): a declaration belongs to the innermost scope around it
        for m in re.finditer(r'\b(?:struct|class|namespace)\s+(?:\w+::)*(\w+)[^;{()]*\{', code):
            depth, i = 1, m.end()
            while i < len(code) and depth:
                depth += {'{': 1, '}': -1}.get(code[i], 0)
                i += 1
            scopes.append((m.start(), i, m.group(1)))
        for d in decl_re.finditer(text):
            ret = d.group(1).strip()
            if ret in ("return", "using", "typedef", "else", "delete", "new"):
                continue
            scope = next((name for start, end, name in reversed(scopes) if start < d.start() < end), "")
            params = []
            for p in _split_template_args(d.group(3)):
                p = p.split("=")[0].strip()
                if p and p != "void":
                    params.append(re.sub(r'\s*\b[A-Za-z_]\w*$', '', p) if re.search(r'[\w>\*&]\s+[A-Za-z_]\w*$', p) else p)
            _HEADER_FUNCS.setdefault((scope, d.group(2)), (ret, params, (d.group(4) or "").strip()))


def bound_header_func(def_text: str) -> Optional[tuple[str, list[str], str]]:
    """The header signature of a `.def("x", &Scope::Name ...)` binding, if it binds a declared function."""
    m = re.search(r'&(\w+)::(\w+)\b', def_text)
    return _HEADER_FUNCS.get((m.group(1), m.group(2))) if m else None


def member_type_from_binding(def_text: str) -> Optional[str]:
    """Python type of a def_readonly/def_readwrite(&Class::Field) or a def_property(_readonly) lambda."""
    m = re.search(r'&(\w+)::(\w+)\b', def_text)
    if m and (m.group(1), m.group(2)) in _HEADER_FIELDS:
        return map_cpp_type(_HEADER_FIELDS[(m.group(1), m.group(2))])
    func = bound_header_func(def_text)   # def_property_readonly("x", &Class::GetX)
    if func:
        return map_cpp_type(func[0])
    raw = extract_lambda_return(def_text)
    return map_cpp_type(raw) if raw else None


