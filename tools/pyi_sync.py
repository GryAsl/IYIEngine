def render_class(cls: ClassDef) -> list[str]:
    lines: list[str] = []

    bases_str = f"({', '.join(cls.bases)})" if cls.bases else ""
    lines.append(f"class {cls.name}{bases_str}:")

    # __init__
    if cls.has_init:
        lines.append(f"    def __init__(self{cls.init_args}) -> None: ...")

    # Members - in order, deduplicated
    seen: set[str] = set()
    for m in cls.members:
        if m.name in seen:
            continue
        seen.add(m.name)

        if m.kind == "readwrite_attr":
            lines.append(f"    {m.name}: {m.py_type}")
        elif m.kind == "readonly_prop":
            lines.append(f"    @property")
            lines.append(f"    def {m.name}(self) -> {m.py_type}: ...")
        elif m.kind == "property_rw":
            lines.append(f"    {m.name}: {m.py_type}")
        elif m.kind == "method":
            args_str = ""
            if m.args:
                args_str = ", " + ", ".join(a.stub_str() for a in m.args)
            lines.append(f"    def {m.name}(self{args_str}) -> {m.ret_type}: ...")
        elif m.kind == "repr":
            lines.append(f"    def __repr__(self) -> str: ...")

    if len(lines) == 1:
        lines.append("    ...")

    return lines


def render_func(f: FuncDef) -> str:
    args_str = ", ".join(a.stub_str() for a in f.args)
    return f"def {f.name}({args_str}) -> {f.ret_type}: ..." + (f"  # {f.doc}" if f.doc else "")


def render_attr(a: AttrDef) -> str:
    return f"{a.name}: {a.py_type}"


