def map_cpp_type(t: str) -> Optional[str]:
    """Map a C++ type string to its Python stub equivalent. Returns None if unknown."""
    t = t.strip()

    # Direct lookup first
    if t in CPP_TO_PY:
        return CPP_TO_PY[t]

    # Strip const/& combinations
    cleaned = re.sub(r'\bconst\b', '', t).replace("&", "").replace(" ", "")
    if cleaned in CPP_TO_PY:
        return CPP_TO_PY[cleaned]

    # Pointer types
    if t.endswith("*"):
        base = re.sub(r'\bconst\b', '', t[:-1]).strip()
        mapped = CPP_TO_PY.get(base)
        if mapped:
            # Raw pointer -> nullable
            if "|" not in mapped:
                return f"{mapped} | None"
            return mapped

    # std::vector<T>
    m = re.match(r'std::vector\s*<(.+)>\s*$', t)
    if m:
        inner = map_cpp_type(m.group(1).strip())
        if inner:
            return f"list[{inner}]"

    # std::optional<T>
    m = re.match(r'std::optional\s*<(.+)>\s*$', t)
    if m:
        inner = map_cpp_type(m.group(1).strip())
        if inner:
            return f"{inner} | None"

    # std::pair<A, B> / std::tuple<A, ...>
    m = re.match(r'std::(?:pair|tuple)\s*<(.+)>\s*$', t)
    if m:
        parts = [map_cpp_type(x) for x in _split_template_args(m.group(1))]
        if all(parts):
            return f"tuple[{', '.join(parts)}]"

    # Same again without const/& around a template (const std::vector<T>& -> std::vector<T>)
    bare = re.sub(r'^\s*const\s+', '', t).rstrip('&').strip()
    if bare != t:
        return map_cpp_type(bare)

    return None


