def find_block_end(text: str, start: int) -> int:
    """
    Starting just after an opening '(', find the matching ')'.
    Returns the index one past the closing ')'.
    """
    depth = 1
    brace_depth = 0
    i = start
    length = len(text)
    while i < length and depth > 0:
        c = text[i]
        if c == '(':
            depth += 1
        elif c == ')':
            depth -= 1
        elif c == '{':
            brace_depth += 1
        elif c == '}':
            brace_depth -= 1
        i += 1
    return i


def _split_template_args(text: str) -> list[str]:
    """
    Split comma-separated C++ template arguments while respecting nested <> and ().
    e.g. "UIButton, UIElement, std::unique_ptr<UIButton, py::nodelete>"
    -> ["UIButton", "UIElement", "std::unique_ptr<UIButton, py::nodelete>"]
    """
    args: list[str] = []
    depth_angle = 0
    depth_paren = 0
    current = ""
    for c in text:
        if c == '<':
            depth_angle += 1
            current += c
        elif c == '>':
            depth_angle -= 1
            current += c
        elif c == '(':
            depth_paren += 1
            current += c
        elif c == ')':
            depth_paren -= 1
            current += c
        elif c == ',' and depth_angle == 0 and depth_paren == 0:
            args.append(current.strip())
            current = ""
        else:
            current += c
    if current.strip():
        args.append(current.strip())
    return args


def parse_binding_file(
    source_path: Path,
    overrides: dict,
) -> tuple[list[ClassDef], list[FuncDef], list[AttrDef], list[ParseError]]:
    """
    Parse a C++ pybind11 binding file.
    Returns (classes, free_funcs, attrs, errors).
    """
    classes: list[ClassDef] = []
    free_funcs: list[FuncDef] = []
    attrs: list[AttrDef] = []
    errors: list[ParseError] = []
    filename = source_path.name

    load_header_fields(source_path.parent.parent / "include")
    load_header_funcs(source_path.parent.parent / "include")
    raw = source_path.read_text(encoding="utf-8", errors="replace")
    # Strip line comments for pattern matching (keep raw for line number lookups)
    stripped = re.sub(r'//[^\n]*', '', raw)

    lines = raw.splitlines()

    # -----------------------------------------------------------------------
    # 1. m.attr() constants
    # -----------------------------------------------------------------------
    for i, line in enumerate(lines):
        m = re.match(r'\s*(?:m|ui)\.attr\("([^"]+)"\)\s*=\s*(.+);', line)
        if m:
            attr_name = m.group(1)
            val = m.group(2).strip()
            if attr_name in COLOR_ATTRS:
                attrs.append(AttrDef(attr_name, "Color"))
            elif "static_cast<int>" in val or re.match(r'^[A-Z0-9_]+$', val.rstrip(";")):
                attrs.append(AttrDef(attr_name, "int"))
            else:
                errors.append(ParseError(filename, i + 1, attr_name,
                    f"m.attr: unrecognized value type: {val[:60]}"))

    # -----------------------------------------------------------------------
    # 2. py::class_ blocks
    # -----------------------------------------------------------------------
    # We need to match py::class_<...> where ... can have nested angle brackets
    # (e.g. py::class_<UIElement, std::unique_ptr<UIElement, py::nodelete>>).
    # Simple [^>]+ fails on nested templates. Use manual scanning instead.
    class_re_prefix = re.compile(r'py::class_<')
    class_decl_re = re.compile(
        r'\(\s*(?:m|ui)\s*,\s*"([^"]+)"[^)]*\)',
        re.DOTALL
    )

    class_ranges: list[tuple[int, int]] = []  # (start, end) char offsets

    def extract_balanced_angles(text: str, start: int) -> tuple[str, int]:
        """Extract balanced <...> content starting at 'start' (pointing at '<')."""
        depth = 0
        i = start
        content_start = start + 1
        while i < len(text):
            c = text[i]
            if c == '<':
                depth += 1
            elif c == '>':
                depth -= 1
                if depth == 0:
                    return text[content_start:i], i + 1
            i += 1
        return text[content_start:], len(text)

    for pm in class_re_prefix.finditer(stripped):
        pos = pm.end() - 1  # points at '<'
        cpp_types_raw, end_pos = extract_balanced_angles(stripped, pos)

        # After >, look for ("ClassName", ...) declaration
        decl_match = class_decl_re.match(stripped, end_pos)
        if not decl_match:
            # Skip - might be a template without a Python binding here
            continue

        py_class_name = decl_match.group(1)
        cpp_types = [t.strip() for t in _split_template_args(cpp_types_raw)]


        # Extract Python base classes (skip unique_ptr, py::nodelete entries)
        bases: list[str] = []
        for t in cpp_types[1:]:
            t2 = t.strip()
            if "unique_ptr" in t2 or "py::nodelete" in t2:
                continue
            py_t = CPP_TO_PY.get(t2)
            if py_t:
                bases.append(py_t)

        # Find the end of the class definition (semicolon at brace/paren depth 0)
        start = pm.start()
        j = decl_match.end()
        b_depth = 0
        p_depth = 0
        length = len(stripped)
        block_end = j
        while j < length:
            c = stripped[j]
            if c == '{':
                b_depth += 1
            elif c == '}':
                b_depth -= 1
            elif c == '(':
                p_depth += 1
            elif c == ')':
                p_depth -= 1
            elif c == ';' and b_depth == 0 and p_depth == 0:
                block_end = j
                break
            j += 1

        class_block = stripped[start:block_end + 1]
        class_ranges.append((start, block_end + 1))

        class_line_no = stripped[:start].count('\n') + 1

        # --- Parse members from class_block ---
        members: list[MemberDef] = []
        seen_names: set[str] = set()

        # Check if class has py::init<>
        has_init = bool(re.search(r'py::init<', class_block)) or py_class_name in KNOWN_INIT_ARGS and bool(KNOWN_INIT_ARGS[py_class_name])
        init_args = KNOWN_INIT_ARGS.get(py_class_name, "")
        if py_class_name in NO_INIT_CLASSES:
            has_init = False
            init_args = ""

        # --- def_readwrite ---
        for m in re.finditer(r'\.def_readwrite\(\s*"([^"]+)"', class_block):
            name = m.group(1)
            if name in seen_names:
                continue
            py_type = (lookup_member_type(py_class_name, name)
                       or member_type_from_binding(class_block[m.start():find_block_end(class_block, m.end())])
                       or "Any")
            members.append(MemberDef(name, py_type, "readwrite_attr"))
            seen_names.add(name)

        # --- def_readonly ---
        for m in re.finditer(r'\.def_readonly\(\s*"([^"]+)"', class_block):
            name = m.group(1)
            if name in seen_names:
                continue
            py_type = (lookup_member_type(py_class_name, name)
                       or member_type_from_binding(class_block[m.start():find_block_end(class_block, m.end())])
                       or "Any")
            members.append(MemberDef(name, py_type, "readonly_prop"))
            seen_names.add(name)

        # --- def_readonly_static (class constants) ---
        for m in re.finditer(r'\.def_readonly_static\(\s*"([^"]+)"', class_block):
            members.append(MemberDef(m.group(1), lookup_member_type(py_class_name, m.group(1)) or "float", "readwrite_attr"))
            seen_names.add(m.group(1))

        # --- def_property_readonly ---
        for m in re.finditer(r'\.def_property_readonly\(\s*"([^"]+)"', class_block):
            name = m.group(1)
            if name in seen_names:
                continue
            py_type = (lookup_member_type(py_class_name, name)
                       or member_type_from_binding(class_block[m.start():find_block_end(class_block, m.end())])
                       or "Any")
            members.append(MemberDef(name, py_type, "readonly_prop"))
            seen_names.add(name)

        # --- def_property ---
        for m in re.finditer(r'\.def_property\(\s*"([^"]+)"', class_block):
            name = m.group(1)
            if name in seen_names:
                continue
            py_type = (lookup_member_type(py_class_name, name)
                       or member_type_from_binding(class_block[m.start():find_block_end(class_block, m.end())])
                       or "Any")
            members.append(MemberDef(name, py_type, "property_rw"))
            seen_names.add(name)

        # --- def (methods) ---
        for m in re.finditer(r'\.def\(\s*"([^"]+)"', class_block):
            name = m.group(1)
            if name in seen_names:
                continue

            # Find extent of this .def() call
            pos = m.end()
            p = 1
            end_pos = pos
            while end_pos < len(class_block) and p > 0:
                c = class_block[end_pos]
                if c == '(':
                    p += 1
                elif c == ')':
                    p -= 1
                end_pos += 1
            def_text = class_block[m.start():end_pos]

            if name == "__repr__":
                members.append(MemberDef("__repr__", "str", "method",
                                         [], "str"))
                seen_names.add(name)
                continue

            if name.startswith("__"):
                seen_names.add(name)
                continue

            # Get args
            py_args = extract_py_args(def_text)
            derived = lambda_arg_types(def_text, py_args, skip_self=True)
            method_args = [Arg(n, arg_type(n, f"{py_class_name}.{name}", t), d) for (n, d), t in zip(py_args, derived)]
            if "py::kwargs" in def_text:
                method_args.append(Arg("**kwargs", "Any"))

            # Get return type
            ret = KNOWN_METHOD_RETURNS.get((py_class_name, name))
            if ret is None:
                # Try lambda extraction
                raw_ret = extract_lambda_return(def_text) or (bound_header_func(def_text) or ("",))[0]
                if raw_ret:
                    ret = map_cpp_type(raw_ret)
                if ret is None:
                    ret = "None"

            members.append(MemberDef(name, ret, "method", method_args, ret))
            seen_names.add(name)

        classes.append(ClassDef(py_class_name, bases, has_init, init_args, members))

    # -----------------------------------------------------------------------
    # 3. Free function m.def() / ui.def() blocks (not inside class ranges)
    # -----------------------------------------------------------------------
    def in_class(pos: int) -> bool:
        for s, e in class_ranges:
            if s <= pos < e:
                return True
        return False

    mdef_re = re.compile(r'(?:m|ui|loc|audio)\.def\s*\(\s*"([^"]+)"')

    for mm in mdef_re.finditer(stripped):
        if in_class(mm.start()):
            continue
        func_name = mm.group(1)
        if func_name.startswith("__"):
            continue

        line_no = stripped[:mm.start()].count('\n') + 1

        # Find extent of m.def(...)
        end_pos = find_block_end(stripped, mm.end())
        def_block = stripped[mm.start():end_pos]

        # Check for override
        if func_name in overrides:
            ov = overrides[func_name]
            ov_args = [Arg(a["name"], a["type"], a.get("default"))
                       for a in ov.get("args", [])]
            ov_ret = ov.get("return", "None")
            free_funcs.append(FuncDef(func_name, ov_args, ov_ret))
            continue

        # Get args
        py_args = extract_py_args(def_block)
        derived = lambda_arg_types(def_block, py_args, skip_self=False)
        func_args = [Arg(n, arg_type(n, func_name, t), d) for (n, d), t in zip(py_args, derived)]
        if "py::pos_only()" in def_block:   # pybind's marker: the args bound before it are positional-only
            before = without_lambda_body(def_block).split("py::pos_only()")[0].count("py::arg(")
            func_args.insert(before, Arg("/", ""))
        if "py::kwargs" in def_block:
            func_args.append(Arg("**kwargs", "Any"))

        # Get return type
        header = bound_header_func(def_block)
        ret = KNOWN_FUNC_RETURNS.get(func_name)
        if ret is None:
            raw_ret = extract_lambda_return(def_block)
            if raw_ret:
                ret = map_cpp_type(raw_ret)
            elif header:
                ret = map_cpp_type(header[0])
            elif lambda_returns_nothing(def_block):
                ret = "None"

        if ret is None:
            # Nothing readable: no known return, no lambda arrow to parse.
            # Emitting a guessed "-> None" would be worse than emitting
            # nothing, because a type checker would then bless wrong calls
            # and reject correct ones. Report it and leave the symbol out.
            errors.append(ParseError(
                filename, line_no, func_name,
                "Return type not resolvable - no lambda arrow, no header declaration "
                "it binds and no entry in KNOWN_FUNC_RETURNS. Add a signature to the "
                "override manifest to include this symbol."))
            continue

        free_funcs.append(FuncDef(func_name, func_args, ret, header[2] if header else ""))

    return classes, free_funcs, attrs, errors


