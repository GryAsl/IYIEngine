class ParseError:
    def __init__(self, source_file: str, line_no: int, symbol: str, reason: str):
        self.source_file = source_file
        self.line_no = line_no
        self.symbol = symbol
        self.reason = reason

    def __str__(self) -> str:
        return f"  {self.source_file}:{self.line_no}: {self.symbol} - {self.reason}"


class Arg:
    def __init__(self, name: str, py_type: str, default: Optional[str] = None):
        self.name = name
        self.py_type = py_type
        self.default = default

    def stub_str(self) -> str:
        if self.name == "/":
            return "/"
        s = f"{self.name}: {self.py_type}"
        if self.default is not None:
            s += f" = {self.default}"
        return s


class MemberDef:
    """A member of a class (property, readwrite attr, or method)."""
    def __init__(self, name: str, py_type: str, kind: str,
                 args: Optional[list[Arg]] = None,
                 ret_type: Optional[str] = None):
        # kind: 'readonly_prop', 'readwrite_attr', 'property_rw', 'method', 'repr'
        self.name = name
        self.py_type = py_type          # for attrs/props
        self.kind = kind
        self.args = args or []
        self.ret_type = ret_type or py_type


class ClassDef:
    def __init__(self, name: str, bases: list[str], has_init: bool, init_args: str,
                 members: list[MemberDef]):
        self.name = name
        self.bases = bases
        self.has_init = has_init
        self.init_args = init_args  # python arg string after 'self'
        self.members = members


class FuncDef:
    def __init__(self, name: str, args: list[Arg], ret_type: str, doc: str = ""):
        self.name = name
        self.args = args
        self.ret_type = ret_type
        self.doc = doc   # the header's trailing comment, shown after the stub line


class AttrDef:
    def __init__(self, name: str, py_type: str):
        self.name = name
        self.py_type = py_type


